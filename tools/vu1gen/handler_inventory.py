#!/usr/bin/env python3
"""VU1 handler entry-point inventory (register-jump-only entries) vs functional engine coverage."""
import re, sys, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
IMG = os.path.join(ROOT, "docs", "vu1_image_86503d39.txt")
INC = os.path.join(ROOT, "PS2Recomp", "ps2xRuntime", "src", "lib", "vu", "vu1_func.inc")
OUT = os.path.join(ROOT, "docs", "VU1_HANDLER_INVENTORY.md")

line_re = re.compile(r"^([0-9A-F]{4}):\s+([0-9a-f]{8})\s+([0-9a-f]{8})\s+(.*?)\s*\|\s*(.*?)\s*$")
pairs = {}
for ln in open(IMG, encoding="utf-8", errors="replace"):
    m = line_re.match(ln)
    if not m:
        continue
    pc = int(m.group(1), 16)
    pairs[pc] = dict(up=m.group(4), lo=m.group(5), uw=int(m.group(2), 16), lw=int(m.group(3), 16))
maxpc = max(pairs)
BR_COND = {"IBEQ", "IBNE", "IBLTZ", "IBGTZ", "IBLEZ", "IBGEZ"}


def mn(p):
    return p["lo"].split()[0].split(".")[0] if p["lo"] else ""


def is_pad(p):
    return p["uw"] == 0 and p["lw"] == 0


def ebit(p):
    return bool(p["uw"] & 0x40000000)


def imm(p):
    return int(p["lo"].split(",")[-1].split()[-1])


targets = set()
for pc, p in pairs.items():
    m = mn(p)
    if m in BR_COND or m in ("B", "BAL"):
        try:
            targets.add((pc + 8 + imm(p) * 8) & 0xFFFF)
        except ValueError:
            pass


def noflow_before(a):
    """True if pair a-8 cannot fall through into a."""
    q = a - 8
    if q not in pairs or is_pad(pairs[q]):
        return True
    if q - 8 in pairs:
        pm = pairs[q - 8]
        if mn(pm) in ("B", "JR") or ebit(pm):  # q is the delay slot of an unconditional jump / E-bit pair
            return True
    return False


cands = []
for a in sorted(pairs):
    if is_pad(pairs[a]):
        continue
    if a in (0, 8) or (a not in targets and noflow_before(a)):
        cands.append(a)
cset = set(cands)

rows = []
for i, a in enumerate(cands):
    # extent: until next candidate or padding or end
    pc = a
    n = 0
    sub = False
    ends = []
    while pc in pairs and not is_pad(pairs[pc]) and (pc == a or pc not in cset):
        p = pairs[pc]
        m = mn(p)
        if m in ("BAL", "JALR", "JR"):
            sub = sub or m in ("BAL", "JALR")
        if ebit(p):
            ends.append("E@%04X" % pc)
        if m == "JR":
            ends.append("%s@%04X" % (p["lo"].replace(" ", ""), pc))
        if m == "B":
            ends.append("B->%04X@%04X" % ((pc + 8 + imm(p) * 8) & 0xFFFF, pc))
        n += 1
        pc += 8
    rows.append((a, n, sub, ", ".join(ends) if ends else "(falls into next)"))

src = open(INC, encoding="utf-8", errors="replace").read().split("\n")
impl = set()
for i, l in enumerate(src):
    if 1340 <= i + 1 <= 1450 or 40 <= i + 1 <= 60:
        for m in re.finditer(r"case 0x([0-9A-Fa-f]+)u:", l):
            impl.add(int(m.group(1), 16))
impl |= {0x0008, 0x0040}  # entry points handled in vu1FuncRun

out = []
out.append("# VU1 handler inventory (image 86503d39)")
out.append("")
out.append("Generated by tools/vu1gen/handler_inventory.py. Candidates = non-padding addresses that are not a static branch target and cannot be fallen into")
out.append("(prev pair is padding, the delay slot of B/JR, or follows an E-bit pair); plus 0000/0008. E-bit = bit 30 of the upper word (image prints no [E]).")
out.append("IMPLEMENTED = `case 0x....u` in vu1_func.inc (lines 40-60 and 1340-1450) plus start PCs 0008/0040.")
out.append("")
out.append("| entry | pairs | impl | calls(BAL/JALR) | ends |")
out.append("|---|---|---|---|---|")
ti = tm = pi = pm_ = 0
missing = []
for a, n, sub, e in rows:
    st = "IMPLEMENTED" if a in impl else "MISSING"
    if a in impl:
        ti += 1; pi += n
    else:
        tm += 1; pm_ += n; missing.append((n, a))
    out.append("| %04X | %d | %s | %s | %s |" % (a, n, st, "yes" if sub else "no", e))
out.append("")
out.append("Totals: %d candidates (%d pairs). IMPLEMENTED %d (%d pairs), MISSING %d (%d pairs)." % (len(rows), ti + tm and sum(r[1] for r in rows), ti, pi, tm, pm_))
missing.sort(reverse=True)
out.append("Biggest MISSING: " + ", ".join("%04X(%d)" % (a, n) for n, a in missing[:12]))
nocand = sorted(x for x in impl if x not in cset)
out.append("Implemented PCs not in candidate list (statically reachable or non-entry): " + ", ".join("%04X" % x for x in nocand))
open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out[-4:]))
print("report lines:", len(out), "->", OUT)
