"""Native-path eligibility for VU1 microcode images other than the main one.

The generated pair executors, hot blocks and kernels are compiled from the main image (86503d39...). Another image can reuse them at every pc where its
decoded pair AND its per-pair usage record (flag/hazard liveness, taken from the same dump the generator reads) are identical to the main image's.
Output: PS2Recomp/.../generated/vu1_variants.inc  (included by vu1_native_dispatch.cpp)
  kVu1HotSpan[2048]   pairs covered by the hot blocks that start at a pc (max n over the recorded variants)
  kVu1Variants[]      {image hash, same[2048]} for every image with a vuusage dump
Usage: python tools/vu1gen/variant_masks.py logs/hotgen_blocks_xl.txt
"""
import glob
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MAIN = "86503d3905e35276"
OUT = os.path.join(REPO, "PS2Recomp/ps2xRuntime/src/lib/vu/generated/vu1_variants.inc")


def load(h):
    d = {}
    for ln in open(os.path.join(REPO, "logs/vuusage_u1_%s.txt" % h)):
        p = ln.split(None, 2)
        if len(p) == 3 and p[0] == "P":
            d[int(p[1], 16) >> 3] = p[2].strip()
    return d


def main():
    span = [0] * 2048
    for ln in open(sys.argv[1]):
        m = re.match(r"B pc=([0-9A-Fa-f]+) .* n=(\d+)", ln)
        if m:
            i = int(m.group(1), 16) >> 3
            span[i] = max(span[i], int(m.group(2)))
    main_u = load(MAIN)
    imgs = sorted(re.search(r"vuusage_u1_([0-9a-f]+)\.txt", f).group(1) for f in glob.glob(os.path.join(REPO, "logs/vuusage_u1_*.txt")))
    o = ["// GENERATED by tools/vu1gen/variant_masks.py -- do not edit.", "const uint8_t kVu1HotSpan[2048] = {"]
    for i in range(0, 2048, 32):
        o.append(" " + ",".join(str(x) for x in span[i:i + 32]) + ",")
    o.append("};")
    rows = []
    for h in imgs:
        if h == MAIN:
            continue
        u = load(h)
        same = [1 if (i in main_u and u.get(i) == main_u[i]) else 0 for i in range(2048)]
        rows.append((h, same))
        print(h, "same pairs", sum(same), "of 2048")
    o.append("struct Vu1Variant { uint64_t hash; uint8_t same[2048]; };")
    o.append("const Vu1Variant kVu1Variants[] = {")
    for h, same in rows:
        o.append(" {0x%sull, {" % h)
        for i in range(0, 2048, 64):
            o.append("  " + ",".join(str(x) for x in same[i:i + 64]) + ",")
        o.append(" }},")
    o.append("};")
    o.append("const uint32_t kVu1VariantCount = %d;" % len(rows))
    open(OUT, "w", newline="\n").write("\n".join(o) + "\n")
    print("wrote", OUT)


main()
