// vucheck_gen: decodes each op word with the REAL recompiler decoder (r5900_decoder.cpp) and emits the C++
// statement the REAL VuTranslator / CodeGenerator::translateVU_* (vu_translator.cpp, vu_translation_helpers.cpp)
// would put into recomp_source. Output: vucheck_ops.inc
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <regex>
#include <string>
#include <vector>

#include "ps2recomp/code_generator.h"
#include "ps2recomp/Translators/vu_translator.h"
#include "ps2recomp/instructions.h"
#include "ps2recomp/types.h"

namespace ps2recomp
{
    // code_generator.cpp is not linked (it drags in the whole recompiler); the ctor/dtor are trivial.
    CodeGenerator::CodeGenerator(const std::vector<Symbol> &symbols, const std::vector<Section> &sections)
        : m_sections(sections)
    {
        for (auto &s : symbols)
            m_symbols.emplace(s.address, s);
    }
    CodeGenerator::~CodeGenerator() = default;
    std::string CodeGenerator::emitUnhandledInstruction(const Instruction &, const std::string &why)
    {
        return "// UNHANDLED: " + why;
    }
}

// r5900_decoder.cpp needs rabbitizer (not available here), so this mirrors the field extraction of
// R5900Decoder::decodeInstruction (lines 56-66, 91) and decodeCOP2 (lines 867-883) for COP2 CO words.
static ps2recomp::Instruction decodeCop2(uint32_t raw)
{
    ps2recomp::Instruction inst;
    inst.address = 0x100000;
    inst.raw = raw;
    inst.opcode = (raw >> 26) & 0x3F;
    inst.rs = (raw >> 21) & 0x1F;
    inst.rt = (raw >> 16) & 0x1F;
    inst.rd = (raw >> 11) & 0x1F;
    inst.sa = (raw >> 6) & 0x1F;
    inst.function = raw & 0x3F;
    inst.immediate = raw & 0xFFFF;
    inst.vectorInfo.vectorField = (raw >> 21) & 0xF;
    const uint32_t s1 = raw & 0x3F;
    const uint32_t vuFunc = s1 >= 0x3C ? ((((raw >> 6) & 0x1F) << 2) | (raw & 3)) : s1;
    if (s1 >= 0x3C && (vuFunc == ps2recomp::VU0_S2_VDIV || vuFunc == ps2recomp::VU0_S2_VRSQRT))
        inst.vectorInfo.fsf = (raw >> 21) & 3;
    if (s1 >= 0x3C && (vuFunc == ps2recomp::VU0_S2_VDIV || vuFunc == ps2recomp::VU0_S2_VSQRT || vuFunc == ps2recomp::VU0_S2_VRSQRT))
        inst.vectorInfo.ftf = (raw >> 23) & 3;
    return inst;
}
static uint32_t enc1(uint32_t f, uint32_t dest, uint32_t ft, uint32_t fs, uint32_t fd)
{
    return 0x4A000000u | (dest << 21) | (ft << 16) | (fs << 11) | (fd << 6) | f;
}
static uint32_t enc2(uint32_t v, uint32_t dest, uint32_t ft, uint32_t fs)
{
    return 0x4A000000u | (dest << 21) | (ft << 16) | (fs << 11) | ((v >> 2) << 6) | (0x3C | (v & 3));
}

int main(int argc, char **argv)
{
    const char *opsPath = argc > 1 ? argv[1] : "tools/vucheck/ops.txt";
    const char *outPath = argc > 2 ? argv[2] : "tools/vucheck/vucheck_ops.inc";
    std::ifstream in(opsPath);
    if (!in) { std::fprintf(stderr, "cannot open %s\n", opsPath); return 1; }

    std::vector<ps2recomp::Symbol> syms;
    std::vector<ps2recomp::Section> secs;
    ps2recomp::CodeGenerator cg(syms, secs);
    ps2recomp::VuTranslator tr(cg);

    struct Op { std::string name; uint32_t word; };
    std::vector<Op> ops;
    std::string line;
    while (std::getline(in, line))
    {
        std::istringstream ss(line);
        std::string n, w;
        if (!(ss >> n >> w)) continue;
        ops.push_back({n, (uint32_t)std::strtoul(w.c_str(), nullptr, 16)});
    }

    std::ofstream out(outPath);
    out << "// GENERATED by vucheck_gen.exe from ops.txt via the real recompiler decoder + VuTranslator. Do not edit.\n";
    auto emit = [&](const std::string &fn, uint32_t word, const std::string &name) -> int {
        ps2recomp::Instruction inst = decodeCop2(word);
        std::string code = tr.translate(inst);
        // VC3: same transformation as tools/fix_vu0_flags.py (regex on mnemonic, lane mask from last _mm_set_epi32 on the blend line)
        bool patched = false;
        {
            static const std::regex mnOk("^v(add|sub|mul|madd|msub|max|mini|opmsub|opmula|adda|suba|mula|madda|msuba)", std::regex::icase);
            static const std::regex setepi("_mm_set_epi32\\(\\s*(-?\\d+),\\s*(-?\\d+),\\s*(-?\\d+),\\s*(-?\\d+)\\s*\\)");
            if (std::regex_search(name, mnOk))
            {
                std::istringstream cs(code);
                std::string ln, res;
                bool pending = true;
                while (std::getline(cs, ln))
                {
                    std::string s = ln;
                    while (!s.empty() && (s.back() == ' ' || s.back() == '\r' || s.back() == '\t')) s.pop_back();
                    if (pending && s.find("_mm_blendv_ps") != std::string::npos && s.find("res") != std::string::npos && !s.empty() && s.back() == '}')
                    {
                        std::smatch m, last;
                        bool any = false;
                        for (auto it = std::sregex_iterator(s.begin(), s.end(), setepi); it != std::sregex_iterator(); ++it) { last = *it; any = true; }
                        if (any)
                        {
                            int w = std::stoi(last[1]) != 0, z = std::stoi(last[2]) != 0, y = std::stoi(last[3]) != 0, x = std::stoi(last[4]) != 0;
                            int mask = x | (y << 1) | (z << 2) | (w << 3);
                            s.pop_back();
                            while (!s.empty() && s.back() == ' ') s.pop_back();
                            s += " ps2x_vu0_flags(ctx, res, " + std::to_string(mask) + "); }";
                            pending = false;
                            patched = true;
                        }
                        ln = s;
                    }
                    res += ln + "\n";
                }
                code = res;
            }
        }
        int flags = 0;
        if (patched) flags |= 8; // bit0 status, bit1 mac, bit2 clip modelled by emitted code
        if (code.find("vu0_status") != std::string::npos) flags |= 1;
        if (code.find("vu0_mac") != std::string::npos) flags |= 2;
        if (code.find("vu0_clip") != std::string::npos) flags |= 4;
        std::string oneline;
        for (char c : code) oneline += (c == '\n' ? ' ' : c);
        out << "// " << name << " 0x" << std::hex << word << std::dec << " flags=" << flags << "\n";
        out << "static void " << fn << "(R5900Context *ctx)\n{\n    " << oneline << "\n}\n";
        return flags;
    };

    emit("op_vmula_seed", enc2(0x2A, 0xF, 7, 6), "VMULA.xyzw vf6*vf7 (seed)");
    emit("op_vmaddx_readback", enc1(0x08, 0xF, 0, 0, 5), "VMADDx.xyzw vf5,vf0,vf0x (readback)");
    std::string table = "static const VuOp kOps[] = {\n";
    for (size_t i = 0; i < ops.size(); ++i)
    {
        char fn[32];
        std::snprintf(fn, sizeof fn, "op_%zu", i);
        int fl = emit(fn, ops[i].word, ops[i].name);
        char buf[160];
        std::snprintf(buf, sizeof buf, "    {\"%s\", 0x%08Xu, %s, %d},\n", ops[i].name.c_str(), ops[i].word, fn, fl);
        table += buf;
    }
    table += "};\n";
    out << table;
    std::printf("vucheck_gen: %zu ops -> %s\n", ops.size(), outPath);
    return 0;
}




